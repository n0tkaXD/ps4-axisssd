#!/usr/bin/env python3
"""Regenerates src/keys.h from LibOrbisPkg's Keys.cs.

Usage: gen_keys.py <path to LibOrbisPkg/Util/Keys.cs>

The fake-pkg entry key 3 is wrapped with the public "PkgDerivedKey3Keyset"
RSA key published by LibOrbisPkg (https://github.com/maxton/LibOrbisPkg,
LGPL-3.0). Only its modulus and private exponent are needed.
"""
import os
import re
import sys

src = open(sys.argv[1]).read()
blk = src[src.index('PkgDerivedKey3Keyset'):]


def field(name):
    m = re.search(name + r'\s*=\s*new byte\[\]\s*\{(.*?)\}', blk, re.S)
    return int.from_bytes(bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(1))), 'big')


n = field('Prime1') * field('Prime2')
d = field('PrivateExponent')


def carray(name, value):
    blob = value.to_bytes(256, 'big')
    rows = [', '.join(f'0x{b:02x}' for b in blob[i:i + 16]) for i in range(0, 256, 16)]
    return f'static const unsigned char {name}[256] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'keys.h')
with open(out, 'w') as f:
    f.write('/* SPDX-License-Identifier: LGPL-3.0-or-later\n'
            ' * Fake pkg entry key 3 (modulus n, private exponent d), derived from the\n'
            ' * PkgDerivedKey3Keyset published by LibOrbisPkg (https://github.com/maxton/LibOrbisPkg).\n'
            ' * Generated by tools/gen_keys.py. */\n#pragma once\n\n')
    f.write(carray('k_pkg_key3_n', n))
    f.write(carray('k_pkg_key3_d', d))
print('wrote', out)
